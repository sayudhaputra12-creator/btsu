CREATE TABLE IF NOT EXISTS admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  username VARCHAR(60) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'Admin' CHECK (role IN ('Admin', 'Super Admin')),
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  last_login_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS login_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(60) NOT NULL,
  failed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_login_attempts_username_time ON login_attempts (username, failed_at);

CREATE TABLE IF NOT EXISTS units (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1))
);

CREATE TABLE IF NOT EXISTS right_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1))
);

CREATE TABLE IF NOT EXISTS districts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1))
);

CREATE TABLE IF NOT EXISTS villages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  district_id BIGINT NOT NULL REFERENCES districts(id),
  name VARCHAR(120) NOT NULL,
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  CONSTRAINT uq_villages_district_name UNIQUE (district_id, name)
);
CREATE INDEX IF NOT EXISTS idx_villages_name ON villages (name);

CREATE TABLE IF NOT EXISTS borrowers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  employee_id VARCHAR(60) NULL UNIQUE,
  unit_id BIGINT NULL REFERENCES units(id) ON DELETE SET NULL,
  phone VARCHAR(40) NULL,
  email VARCHAR(190) NULL,
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_borrowers_name ON borrowers (name);

CREATE TABLE IF NOT EXISTS documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  province VARCHAR(80) NOT NULL DEFAULT 'Jawa Tengah',
  city VARCHAR(100) NOT NULL DEFAULT 'Semarang',
  district VARCHAR(100) NOT NULL,
  village VARCHAR(120) NOT NULL,
  right_category_id BIGINT NOT NULL REFERENCES right_categories(id),
  right_number VARCHAR(80) NOT NULL,
  document_date DATE NULL,
  floor INTEGER NOT NULL CHECK (floor >= 0),
  cabinet INTEGER NOT NULL CHECK (cabinet >= 0),
  rack VARCHAR(30) NOT NULL,
  album VARCHAR(80) NULL,
  condition_state VARCHAR(30) NOT NULL DEFAULT 'Baik' CHECK (condition_state IN ('Baik', 'Perlu perbaikan', 'Rusak')),
  status VARCHAR(30) NOT NULL DEFAULT 'Tersedia' CHECK (status IN ('Tersedia', 'Dipinjam', 'Hilang', 'Nonaktif')),
  notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_documents_location_number UNIQUE (district, village, right_category_id, right_number)
);
CREATE INDEX IF NOT EXISTS idx_documents_status ON documents (status);
CREATE INDEX IF NOT EXISTS idx_documents_number ON documents (right_number);
CREATE INDEX IF NOT EXISTS idx_documents_village ON documents (village);
CREATE INDEX IF NOT EXISTS idx_documents_district ON documents (district);
CREATE INDEX IF NOT EXISTS idx_documents_category ON documents (right_category_id);

CREATE OR REPLACE FUNCTION update_documents_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_documents_updated_at ON documents;
CREATE TRIGGER trg_documents_updated_at
BEFORE UPDATE ON documents
FOR EACH ROW
EXECUTE FUNCTION update_documents_updated_at();

CREATE TABLE IF NOT EXISTS loans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  borrower_id BIGINT NOT NULL REFERENCES borrowers(id),
  admin_id BIGINT NOT NULL REFERENCES admins(id),
  loan_date DATE NOT NULL,
  due_date DATE NOT NULL,
  purpose VARCHAR(255) NOT NULL,
  notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_loans_borrower ON loans (borrower_id);
CREATE INDEX IF NOT EXISTS idx_loans_due_date ON loans (due_date);
CREATE INDEX IF NOT EXISTS idx_loans_admin ON loans (admin_id);

CREATE TABLE IF NOT EXISTS loan_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id BIGINT NOT NULL REFERENCES loans(id),
  document_id BIGINT NOT NULL REFERENCES documents(id),
  returned_at DATE NULL,
  return_condition VARCHAR(30) NULL CHECK (return_condition IS NULL OR return_condition IN ('Baik', 'Perlu perbaikan', 'Rusak', 'Hilang')),
  return_note TEXT NULL,
  active_document_id BIGINT GENERATED ALWAYS AS (
    CASE WHEN returned_at IS NULL THEN document_id ELSE NULL END
  ) STORED,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_one_active_loan_per_document UNIQUE (active_document_id)
);
CREATE INDEX IF NOT EXISTS idx_loan_items_loan ON loan_items (loan_id);
CREATE INDEX IF NOT EXISTS idx_loan_items_document ON loan_items (document_id);
CREATE INDEX IF NOT EXISTS idx_loan_items_returned ON loan_items (returned_at);

CREATE TABLE IF NOT EXISTS loan_extensions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id BIGINT NOT NULL REFERENCES loans(id),
  admin_id BIGINT NOT NULL REFERENCES admins(id),
  old_due_date DATE NOT NULL,
  new_due_date DATE NOT NULL,
  reason VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_loan_extensions_loan ON loan_extensions (loan_id);

CREATE TABLE IF NOT EXISTS settings (
  setting_key VARCHAR(60) PRIMARY KEY,
  setting_value VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id BIGINT NULL REFERENCES admins(id) ON DELETE SET NULL,
  action VARCHAR(120) NOT NULL,
  detail VARCHAR(500) NOT NULL DEFAULT '',
  ip_address VARCHAR(45) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs (created_at);
